}

/**
 * Creates the installation lock file.
 *
 * @param array $metadata
 * @return bool
 */
function create_installation_lock(array $metadata = []): bool
{
    $lockData = array_merge([
        'installed_at' => date('c'),
        'version'      => '9.0.0',
        'status'       => 'locked'
    ], $metadata);

    // Filter out any accidental credential fields
    unset($lockData['db_password'], $lockData['password'], $lockData['admin_password']);

    $content = json_encode($lockData, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
    return (file_put_contents(INSTALL_LOCK_FILE, $content, LOCK_EX) !== false);
}

/**
 * Parses and executes a multi-statement SQL script using PDO.
 * Properly handles comments (-- , #, /* * /), quoted strings, and multi-line statements.
 *
 * @param PDO $pdo
 * @param string $sqlContent
 * @return array ['success' => bool, 'statements_executed' => int, 'error' => string|null]
 */
function run_sql_import(PDO $pdo, string $sqlContent): array
{
    $statements = [];
    $buffer = '';
    $inSingleQuote = false;
    $inDoubleQuote = false;
    $inBacktick = false;
    $len = strlen($sqlContent);
    $i = 0;

    while ($i < $len) {
        $char = $sqlContent[$i];
        $next = ($i + 1 < $len) ? $sqlContent[$i + 1] : '';

        // Check for comment starts if not inside quotes
        if (!$inSingleQuote && !$inDoubleQuote && !$inBacktick) {
            // Multi-line comment /* ... */
            if ($char === '/' && $next === '*') {
                $closePos = strpos($sqlContent, '*/', $i + 2);
                if ($closePos === false) {
                    $i = $len; // Unclosed comment till EOF
                } else {
                    $i = $closePos + 2;
                }
                continue;
            }

            // Single line comment -- or #
            if (($char === '-' && $next === '-') || $char === '#') {
                $nlPos = strpos($sqlContent, "\n", $i);
                if ($nlPos === false) {
                    $i = $len;
                } else {
                    $i = $nlPos + 1;
                }
                continue;
            }
        }

        // Handle quotes
        if ($char === "'" && !$inDoubleQuote && !$inBacktick) {
            if ($inSingleQuote) {
                // Check if escaped with \' or ''
                $prev = ($i > 0) ? $sqlContent[$i - 1] : '';
                if ($prev !== '\\') {
                    $inSingleQuote = false;
                }
            } else {
                $inSingleQuote = true;
            }
        } elseif ($char === '"' && !$inSingleQuote && !$inBacktick) {
            if ($inDoubleQuote) {
                $prev = ($i > 0) ? $sqlContent[$i - 1] : '';
                if ($prev !== '\\') {
                    $inDoubleQuote = false;
                }
            } else {
                $inDoubleQuote = true;
            }
        } elseif ($char === '`' && !$inSingleQuote && !$inDoubleQuote) {
            $inBacktick = !$inBacktick;
        }

        // Check for statement terminator ';'
        if ($char === ';' && !$inSingleQuote && !$inDoubleQuote && !$inBacktick) {
            $stmt = trim($buffer);
            if (!empty($stmt)) {
                $statements[] = $stmt;
            }
            $buffer = '';
            $i++;
            continue;
        }

        $buffer .= $char;
        $i++;
    }

    $lastStmt = trim($buffer);
    if (!empty($lastStmt)) {
        $statements[] = $lastStmt;
    }

    $count = 0;
    foreach ($statements as $stmt) {
        if (empty($stmt)) {
            continue;
        }
        try {
            $pdo->exec($stmt);
            $count++;
        } catch (PDOException $e) {
            return [
                'success'             => false,
                'statements_executed' => $count,
                'error'               => 'SQL execution error: ' . $e->getMessage(),
                'statement'           => mb_substr($stmt, 0, 150) . '...'
            ];
        }
    }

    return [
        'success'             => true,
        'statements_executed' => $count,
        'error'               => null
    ];
}
